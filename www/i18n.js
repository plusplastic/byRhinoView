export let currentLang = 'en';

// ── Core functions ─────────────────────────────────────────────────────────────

/**
 * Translate a key for the current language, falling back to English, then the
 * raw key if no translation exists at all.
 */
export function t(key) {
  return TRANSLATIONS[currentLang]?.[key] ?? TRANSLATIONS['en'][key] ?? key;
}

/**
 * Set the active language, persist to localStorage, and re-apply translations
 * to the DOM.
 */
export function setLang(code) {
  if (TRANSLATIONS[code]) {
    currentLang = code;
    try {
      localStorage.setItem('byrhinoview_lang', code);
    } catch (e) {
      console.warn('Failed to save language to localStorage:', e);
    }
    applyI18n();
  }
}

/**
 * Walk the DOM and update every element that carries a `data-i18n` or
 * `data-i18n-title` attribute with the translated string for the current
 * language.
 */
export function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key  = el.dataset.i18n;
    const text = t(key);
    if (el.tagName === 'INPUT' && el.placeholder !== undefined) {
      el.placeholder = text;
    } else {
      el.textContent = text;
    }
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
}

/**
 * Detect and restore the preferred language from localStorage or the browser
 * locale.  Call this once on startup before the first render.
 */
export function initI18n() {
  let saved = null;
  try {
    saved = localStorage.getItem('byrhinoview_lang');
  } catch (e) {
    console.warn('Failed to read language from localStorage:', e);
  }
  if (saved && TRANSLATIONS[saved]) {
    currentLang = saved;
  } else {
    const browserLang = navigator.language?.toLowerCase();
    if      (browserLang?.startsWith('ko'))                                         currentLang = 'ko';
    else if (browserLang?.startsWith('ja'))                                         currentLang = 'ja';
    else if (browserLang?.startsWith('zh-tw') || browserLang?.startsWith('zh-hant')) currentLang = 'zh-TW';
    else if (browserLang?.startsWith('zh'))                                         currentLang = 'zh-CN';
    else if (browserLang?.startsWith('fr'))                                         currentLang = 'fr';
    else if (browserLang?.startsWith('de'))                                         currentLang = 'de';
    else if (browserLang?.startsWith('es'))                                         currentLang = 'es';
    else if (browserLang?.startsWith('it'))                                         currentLang = 'it';
    else if (browserLang?.startsWith('pt'))                                         currentLang = 'pt-BR';
    else if (browserLang?.startsWith('cs'))                                         currentLang = 'cs';
    else if (browserLang?.startsWith('pl'))                                         currentLang = 'pl';
    // default remains 'en'
  }
}
